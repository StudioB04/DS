// Concatenates the real DS theme (reset + tokens, including the light and dark
// themes) into one static CSS file, served as is by the sandbox through
// .sandbox/index.html (<link rel="stylesheet" href="/theme.css">) instead of a
// Vite/Tailwind import.
//
// Why: Tailwind's CSS engine (Lightning CSS) dropped part of these files twice
// once they were mixed into its own processing: first all of light.css and
// dark.css (a misplaced @import once inlined), then only some of their
// declarations (silently, in dev). Rather than keep chasing that behaviour, this
// script takes the DS theme out of the Tailwind pipeline: the browser parses a
// static, untransformed file. Tailwind only generates the utility classes
// (tailwind-theme.css).
//
// The file is regenerated on every `npm run sandbox` (see the "theme" script in
// .sandbox/package.json). It starts with the layer order declared in
// .sandbox/sandbox.css, so the order holds whichever stylesheet loads first.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const stylesDir = resolve(__dirname, "../src/styles");
const outDir = resolve(__dirname, "public");
const outFile = resolve(outDir, "theme.css");

const IMPORT_RE = /@import\s+url\(["']?(.+?)["']?\)\s*;/g;

// Recursively resolves the @import url("...") rules of a CSS file by inlining
// their content (the DS tokens only import each other, with relative paths, so
// no more complex resolver is needed).
function resolveImports(filePath, seen = new Set()) {
  if (seen.has(filePath)) return ""; // avoids duplicates and loops
  seen.add(filePath);

  const raw = readFileSync(filePath, "utf8");
  const dir = dirname(filePath);

  return raw.replace(IMPORT_RE, (_match, importPath) => {
    const resolved = resolve(dir, importPath);
    return resolveImports(resolved, seen);
  });
}

// A single `seen` shared by all entry files: tokens.css already imports
// light.css and dark.css, so listing them here too would only inline them a
// second time.
const seen = new Set();
const parts = [
  `/* Generated by .sandbox/build-theme.mjs -- do not edit by hand. */`,
  resolveImports(resolve(stylesDir, "reset.css"), seen),
  resolveImports(resolve(stylesDir, "themes/tokens.css"), seen),
];

const layerOrder = /^@layer [\w\s,-]+;/m.exec(readFileSync(resolve(__dirname, "sandbox.css"), "utf8"))?.[0];
if (!layerOrder) throw new Error("No @layer order statement found in sandbox.css");

const content = `${layerOrder}\n\n@layer theme {\n${parts.join("\n\n")}\n}\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, content, "utf8");
console.log(`✓ ${outFile} generated (${content.length} bytes)`);
